export function bdSubjectId(stage: BdStageId, key: string) {
  return `bd-${stage}-${key}`;
}

/** Every NCTB book as an app subject. */
export const bdSubjects: Subject[] = (Object.entries(books) as [BdStageId, Book[]][]).flatMap(([stage, list]) =>
  list.map((b) => ({
    id: bdSubjectId(stage, b.key),
    name: b.name,
    nameBn: b.nameBn,
    emoji: "",
    blurb: b.blurb,
    units: b.chapters.map(([en]) => en),
    unitsBn: b.chapters.map(([, bn]) => bn),
    curriculum: "nctb" as const,
    stage,
    groups: b.groups,
    kind: b.kind,
  })),
);

/** The books a student in this class (and group, from Class 9) studies, compulsory ones first. */
export function bdSubjectsFor(stage: BdStageId | "", group: BdGroup | "" = ""): Subject[] {
  if (!stage) return [];
  const list = bdSubjects.filter((s) => s.stage === stage && (!s.groups || (group !== "" && s.groups.includes(group))));
  return [...list.filter((s) => !s.groups), ...list.filter((s) => s.groups)];
}

export function bdStage(id: BdStageId | "" | undefined): BdStage | undefined {
  return bdStages.find((s) => s.id === id);
}
