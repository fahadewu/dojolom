// Regenerates src/content/index.ts from the unit files that exist on disk.
// Run after adding or removing a unit: node scripts/gen-content-index.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src", "content");
const entries = [];
for (const subject of readdirSync(root).sort()) {
  const dir = join(root, subject);
  if (!statSync(dir).isDirectory()) continue;
  for (const f of readdirSync(dir).sort()) {
    const m = f.match(/^unit-(\d)\.ts$/);
    if (m) entries.push({ subject, unit: Number(m[1]) });
  }
}
entries.sort((a, b) => a.subject.localeCompare(b.subject) || a.unit - b.unit);
const lines = entries.map((e) => `  "${e.subject}-${e.unit}": () => import("./${e.subject}/unit-${e.unit}"),`);
const out = `// Generated by scripts/gen-content-index.mjs. Do not edit by hand.
// One lazy import per authored unit, so a learner only downloads the subjects they chose.
import type { UnitContent } from "./types";

export type UnitKey = \`\${string}-\${number}\`;
export type UnitLoader = () => Promise<{ default: UnitContent }>;

export const contentIndex: Record<string, UnitLoader> = {
${lines.join("\n")}
};

export const authoredUnits = Object.keys(contentIndex);
`;
writeFileSync(join(root, "index.ts"), out);
console.log(`content index: ${entries.length} units`);
